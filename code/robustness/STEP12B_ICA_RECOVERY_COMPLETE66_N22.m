%% STEP12B_ICA_RECOVERY_COMPLETE66_N22.m
% Article2 reviewer-focused ICA sensitivity analysis (N=22).
%
% PURPOSE
% -------
% This script repeats the FINAL Article1-matched spectral pipeline after a
% conservative, condition-blind ICA artifact-removal step. ICA is fitted on
% each continuous task recording (not on the 0-0.6 s analysis epochs).
% ICLabel is then used to remove only high-confidence Eye and Muscle
% components (probability >= 0.90). The same ICA decomposition is reused for
% both the primary and equal-duration spectral branches.
%
% The goal is NOT to replace the final pipeline automatically. It tests
% whether the maintenance-centered spectral pattern, posterior alpha, and
% posterior gamma remain qualitatively robust after ICA cleaning.
%
% STEP12B RECOVERY NOTE
% ---------------------
% The first STEP12 run completed ICLabel for only a subset of the 66 task
% recordings. STEP12B reuses every available STEP12 ICA decomposition, fits
% ICA only for recordings without a reusable decomposition, then classifies
% ALL recordings uniformly with the validated ICLabel 'lite' classifier.
% The lite classifier omits autocorrelation features, which avoids the
% feature-extraction failures observed in MATLAB R2021a while retaining the
% ICLabel topography + PSD classifier. A deterministic 120-s centered segment
% is used for IC classification; ICA itself is still fitted on the full
% continuous recording. The script requires complete 66/66 run coverage
% before producing the final robustness decision.
%
% IMPORTANT: The FINAL analysis windows remain exactly:
%   stimulus / early encoding: 0 to 0.6 s
%   maintenance             : 0 to 1.0 s
%   retrieval               : 0 to 0.6 s
% Equal-duration direct-phase sensitivity remains 0 to 0.6 s for all phases.
%
% IMPORTANT
% ---------
% This version does NOT require an EEG_clean folder.
% It uses:
%   1) STEP09A2_MergedTrialPhaseTable.csv
%   2) raw task MAT files under the IPM/Subjects archive
%   3) TaskEEG_ChannelBand_SubjectFeatures_FINAL.csv only to recover/verify
%      the final N=22 subject set.
%
% One fixed preprocessing/extraction path is used. No extraction-mode
% selection is performed from the statistical results.
%
% FINAL PRIMARY TASK-PERIOD WINDOWS (matched to revised Article1):
%   stimulus / early encoding: 0 to 0.6 s from stimulus onset
%   maintenance             : 0 to 1.0 s from maintenance onset
%   retrieval               : 0 to 0.6 s from retrieval onset
% The pre-event interval is NOT included in spectral feature calculation.
%
% DIRECT PHASE SENSITIVITY BRANCH:
%   stimulus, maintenance, retrieval: identical 0 to 0.6 s post-onset windows
% This branch is used only for direct cross-phase condition-effect magnitude
% comparisons so that unequal primary window lengths do not bias that test.
%
% MATLAB R2021a compatible.
%
% Main outputs:
%   STEP12BICA_PRIMARY_Article1Matched_SubjectChannelFeatures_N22.csv
%   STEP12BICA_PRIMARY_Article1Matched_SubjectROIFeatures_N22.csv
%   STEP12BICA_PRIMARY_Article1Matched_Channel_Omnibus.csv
%   STEP12BICA_PRIMARY_Article1Matched_ROI_Omnibus.csv
%   STEP12BICA_EQUAL0600_Channel_Omnibus.csv
%   STEP12BICA_EQUAL0600_ROI_Omnibus.csv
%   STEP12BICA_EQUAL0600_FocusedIndices_DirectPhase_Omnibus.csv
%   (ERP branch intentionally skipped in STEP12)
%   STEP12BICA_DirectPhase_SupportSummary.csv
%   STEP12BICA_ManuscriptDecisionSummary.csv
%
% This script does not overwrite previous analyses.

clear; clc; close all;
rng(7,'twister');

%% ============================= CONFIG =============================
cfg = struct();

cfg.rootDir = uigetdir(pwd, 'Select the Article2 Analysis folder');
if isequal(cfg.rootDir,0)
    error('Article2 Analysis folder was not selected.');
end
cfg.articleRoot = fileparts(cfg.rootDir);

% The raw recordings in this project are primarily MAT files, not EDF.
% Project-relative candidates are tried first; otherwise the user is prompted.
cfg.rawRootCandidates = { ...
    fullfile(cfg.rootDir,'Subjects'), ...
    fullfile(cfg.articleRoot,'Subjects') ...
    };
cfg.rawRoot = firstExistingDir(cfg.rawRootCandidates);

cfg.outDir = fullfile(cfg.rootDir,'Result', ...
    'STEP12B_ICA_RECOVERY_COMPLETE66_N22');
if ~exist(cfg.outDir,'dir'); mkdir(cfg.outDir); end
cfg.figDir = fullfile(cfg.outDir,'figures');
if ~exist(cfg.figDir,'dir'); mkdir(cfg.figDir); end

% Existing trial-phase table generated by STEP09A2.
cfg.mergedTableCandidates = { ...
    fullfile(cfg.rootDir,'Result','STEP10_FINAL_ARTICLE1_MATCHED_WINDOWS_N22', ...
        'STEP10_MergedTrialPhaseTable_N22_Repaired.csv'), ...
    fullfile(cfg.rootDir,'Result','STEP09A2_ConditionERP_Windows_N22', ...
        'STEP09A2_MergedTrialPhaseTable.csv'), ...
    fullfile(cfg.rootDir,'STEP09A2_ConditionERP_Windows_N22', ...
        'STEP09A2_MergedTrialPhaseTable.csv'), ...
    fullfile(cfg.rootDir,'STEP09A2_MergedTrialPhaseTable.csv') ...
    };

% Existing final spectral table. It is used only to recover/verify the final N=22 set.
cfg.finalFeatureCandidates = { ...
    fullfile(cfg.rootDir,'STEP03V3_TaskEEG_FinalQC', ...
        'TaskEEG_ChannelBand_SubjectFeatures_FINAL.csv'), ...
    fullfile(cfg.rootDir,'Result','STEP03V3_TaskEEG_FinalQC', ...
        'TaskEEG_ChannelBand_SubjectFeatures_FINAL.csv'), ...
    fullfile(cfg.rootDir,'TaskEEG_ChannelBand_SubjectFeatures_FINAL.csv') ...
    };

% ERP is deliberately NOT reused here: the purpose of STEP12 is to test
% spectral robustness after ICA. Reusing a non-ICA ERP table would mix
% preprocessing branches. A separate ICA-ERP sensitivity can be added later
% only if needed.
cfg.erpCandidates = {};

cfg.finalSubjectsFallback = [ ...
    "s1";"s2";"s3";"s4";"s5";"s6";"s7";"s8";"s9"; ...
    "s11";"s12";"s13";"s14";"s15";"s16";"s17"; ...
    "s18";"s19";"s20";"s21";"s22";"s23" ...
    ];

cfg.targetPhases = ["stimulus","maintenance","retrieval"];
cfg.targetConditions = ["color","orientation","conjunction"];

cfg.fsDefault = 250;
cfg.maxChannels = 64;
% Primary phase windows, matched exactly to revised Article1.
cfg.primaryWindowSec = struct();
cfg.primaryWindowSec.stimulus    = 0.6;
cfg.primaryWindowSec.maintenance = 1.0;
cfg.primaryWindowSec.retrieval   = 0.6;

% Equal post-onset window used ONLY for direct cross-phase sensitivity.
cfg.sensitivityWindowSec = 0.6;

% Spectral extraction excludes the pre-event baseline interval.
cfg.usePreEventBaselineForSpectral = false;
cfg.useHamming = true;

cfg.bandNames = ["delta","theta","alpha","beta","gamma"];
cfg.bandRanges = [1 4; 4 8; 8 13; 13 30; 30 45];
cfg.logOffset = 1e-12;

cfg.minSubjectsForStats = 15;
cfg.alpha = 0.05;
cfg.saveWorkspace = true;
cfg.makeFigures = false;

% Reference final non-ICA STEP10 outputs used only for robustness comparison.
cfg.referenceStep10Dir = fullfile(cfg.rootDir,'Result', ...
    'STEP10_FINAL_ARTICLE1_MATCHED_WINDOWS_N22');

% Conservative ICA sensitivity settings.
cfg.ica = struct();
cfg.ica.enabled = true;
cfg.ica.fitHighpassHz = 1.0;   % ICA fit copy only; analysis data remain 0.5-45 Hz.
cfg.ica.eyeThreshold = 0.90;
cfg.ica.muscleThreshold = 0.90;
cfg.ica.maxRejectFractionWarning = 0.35; % QC warning only; does not change thresholding.
cfg.ica.modelDir = fullfile(cfg.outDir,'ica_models');
cfg.ica.qcDir = fullfile(cfg.outDir,'ica_component_qc');
if ~exist(cfg.ica.modelDir,'dir'); mkdir(cfg.ica.modelDir); end
if ~exist(cfg.ica.qcDir,'dir'); mkdir(cfg.ica.qcDir); end

% STEP12B recovery settings.
% Reuse the expensive ICA decompositions from the original STEP12 whenever
% available, but re-run ICLabel uniformly for all recordings with 'lite'.
cfg.ica.previousStep12ModelDir = fullfile(cfg.rootDir,'Result', ...
    'STEP12_ICA_SENSITIVITY_N22','ica_models');
cfg.ica.decompDir = fullfile(cfg.outDir,'ica_decompositions');
if ~exist(cfg.ica.decompDir,'dir'); mkdir(cfg.ica.decompDir); end
cfg.ica.classifierVersion = 'lite';
cfg.ica.classificationSegmentSec = 120;
cfg.ica.classificationFallbackSec = [120 60 30];
cfg.ica.requireCompleteRunCoverage = true;

% Initialize EEGLAB + ICLabel. The script stops rather than silently
% substituting a different automatic ICA classifier.
cfg = initializeEEGLABAndICLabel(cfg);

cfg.roi = defineSpectralROIs();

%% =========================== FILE LOCATORS =========================
cfg.mergedFile = firstExistingFile(cfg.mergedTableCandidates);
if isempty(cfg.mergedFile)
    [f,p] = uigetfile('*.csv', ...
        'Select STEP09A2_MergedTrialPhaseTable.csv', cfg.rootDir);
    if isequal(f,0)
        error(['Merged trial-phase table not selected. Run STEP09A2 first, ' ...
            'or select STEP09A2_MergedTrialPhaseTable.csv.']);
    end
    cfg.mergedFile = fullfile(p,f);
end

cfg.finalFeatureFile = firstExistingFile(cfg.finalFeatureCandidates);
if isempty(cfg.finalFeatureFile)
    [f,p] = uigetfile('*.csv', ...
        'Select TaskEEG_ChannelBand_SubjectFeatures_FINAL.csv', cfg.rootDir);
    if isequal(f,0)
        error(['Final feature table is required to recover/verify the final N=22 set. ' ...
            'Select TaskEEG_ChannelBand_SubjectFeatures_FINAL.csv.']);
    end
    cfg.finalFeatureFile = fullfile(p,f);
end

cfg.erpFile = firstExistingFile(cfg.erpCandidates);

if isempty(cfg.rawRoot) || exist(cfg.rawRoot,'dir')~=7
    selectedRoot = uigetdir(pwd, ...
        'Select the IPM Subjects folder containing the raw MAT files');
    if isequal(selectedRoot,0)
        error('Raw Subjects folder was not selected.');
    end
    cfg.rawRoot = selectedRoot;
end

reportFile = fullfile(cfg.outDir, ...
    'STEP12BICA_RunReport.txt');
if exist(reportFile,'file'); delete(reportFile); end
diary(reportFile);
diaryCleanup = onCleanup(@() diary('off')); %#ok<NASGU>

fprintf('============================================================\n');
fprintf('STEP12B ICA RECOVERY: COMPLETE-RUN ARTICLE1-MATCHED SPECTRAL ANALYSIS\n');
fprintf('Generated: %s\n',datestr(now));
fprintf('MATLAB: %s\n',version);
fprintf('Merged table: %s\n',cfg.mergedFile);
fprintf('Final feature table: %s\n',cfg.finalFeatureFile);
fprintf('Raw root: %s\n',cfg.rawRoot);
fprintf('Output: %s\n',cfg.outDir);
fprintf('Primary windows: stimulus 0-%.3f s | maintenance 0-%.3f s | retrieval 0-%.3f s\n', ...
    cfg.primaryWindowSec.stimulus,cfg.primaryWindowSec.maintenance,cfg.primaryWindowSec.retrieval);
fprintf('Direct-phase sensitivity window: 0-%.3f s for every phase\n',cfg.sensitivityWindowSec);
fprintf('ICLabel classifier: %s | classification segment: centered %.0f s\n', ...
    cfg.ica.classifierVersion,cfg.ica.classificationSegmentSec);
fprintf('Pre-event baseline included in spectral feature calculation: %d\n', ...
    cfg.usePreEventBaselineForSpectral);
fprintf('============================================================\n');

%% ======================= LOAD AND STANDARDIZE =====================
Mraw = readtable(cfg.mergedFile,'TextType','string', ...
    'VariableNamingRule','preserve');
M = standardizeMergedTable(Mraw);

Fraw = readtable(cfg.finalFeatureFile,'TextType','string', ...
    'VariableNamingRule','preserve');
F = standardizeFinalFeatureTable(Fraw);

if isempty(F)
    error('The selected final feature table could not be standardized.');
end

finalSubjects = unique(F.Subject,'stable');
finalSubjects = finalSubjects(strlength(finalSubjects)>0);
if numel(finalSubjects)~=22
    warning(['Final feature table contains %d unique subjects. ' ...
        'Using the fixed N=22 fallback list.'],numel(finalSubjects));
    finalSubjects = cfg.finalSubjectsFallback;
end
cfg.finalSubjects = finalSubjects(:);

fprintf('\nFinal subjects (%d): %s\n',numel(cfg.finalSubjects), ...
    strjoin(cellstr(cfg.finalSubjects),', '));

% Ensure raw EDF paths exist. Invalid/empty paths are remapped from rawRoot.
[M,rawMap] = repairRawPaths(M,cfg.rawRoot);
writetable(rawMap,fullfile(cfg.outDir,'STEP12BICA_RawFileInventory.csv'));

keep = ismember(M.Subject,cfg.finalSubjects) & ...
       ismember(M.ConditionLabel,cfg.targetConditions) & ...
       ismember(M.PhaseLabel,cfg.targetPhases) & ...
       isfinite(M.PhaseStartSample) & M.PhaseStartSample>0 & ...
       strlength(M.RawEEGPath)>0;

M = M(keep,:);
M = unique(M(:,intersect( ...
    {'Subject','Run','Trial','ConditionLabel','PhaseLabel', ...
     'PhaseStartSample','RawEEGPath'}, ...
    M.Properties.VariableNames,'stable')),'rows','stable');

if isempty(M)
    error('No usable N=22 trial-phase rows remained after path repair.');
end

fprintf('Usable trial-phase rows: %d\n',height(M));
fprintf('Usable raw EDF files: %d\n',numel(unique(M.RawEEGPath)));
fprintf('Subjects represented: %d\n',numel(unique(M.Subject)));

writetable(M,fullfile(cfg.outDir, ...
    'STEP12BICA_MergedTrialPhaseTable_N22_Repaired.csv'));

Tcoverage = makeCoverageTable(M,cfg);
writetable(Tcoverage,fullfile(cfg.outDir, ...
    'STEP12BICA_QC_TrialPhaseCoverage_BeforeExtraction.csv'));

%% ================= FINAL ARTICLE1-MATCHED EXTRACTION =================
% One fixed preprocessing/extraction path is used:
%   continuous 0.5-45 Hz band-pass, 50-Hz notch, average rereference,
%   event-locked post-onset segment only, Hamming window, FFT band power.
%
% Primary phase windows:
%   stimulus    0-0.6 s
%   maintenance 0-1.0 s
%   retrieval   0-0.6 s
%
% Direct phase sensitivity:
%   0-0.6 s for all three phases.

primaryMode = "article1_primary";
sensitivityMode = "equal0600_sensitivity";

fprintf('\n============================================================\n');
fprintf('EXTRACTING PRIMARY ARTICLE1-MATCHED WINDOWS\n');
fprintf('============================================================\n');

[TchanPrimary,TlogPrimary] = extractSubjectSpectralFeaturesFinal( ...
    M,cfg,primaryMode);

writetable(TchanPrimary,fullfile(cfg.outDir, ...
    'STEP12BICA_PRIMARY_Article1Matched_SubjectChannelFeatures_N22.csv'));
writetable(TlogPrimary,fullfile(cfg.outDir, ...
    'STEP12BICA_PRIMARY_Article1Matched_ReadLog.csv'));

fprintf('\n============================================================\n');
fprintf('EXTRACTING EQUAL 0-0.6 s DIRECT-PHASE SENSITIVITY WINDOWS\n');
fprintf('============================================================\n');

[TchanSensitivity,TlogSensitivity] = extractSubjectSpectralFeaturesFinal( ...
    M,cfg,sensitivityMode);

writetable(TchanSensitivity,fullfile(cfg.outDir, ...
    'STEP12BICA_EQUAL0600_Equal0600_SubjectChannelFeatures_N22.csv'));
writetable(TlogSensitivity,fullfile(cfg.outDir, ...
    'STEP12BICA_EQUAL0600_Equal0600_ReadLog.csv'));

%% ===================== COMPLETE-RUN ICA COVERAGE ====================
[TicaRunCoverage,TicaCoverageSummary] = makeICARunCoverageAudit( ...
    M,TlogPrimary,TlogSensitivity);
writetable(TicaRunCoverage,fullfile(cfg.outDir, ...
    'STEP12BICA_ICA_RunCoverage_66.csv'));
writetable(TicaCoverageSummary,fullfile(cfg.outDir, ...
    'STEP12BICA_ICA_RunCoverage_Summary.csv'));

fprintf('\n================ ICA RUN COVERAGE =================\n');
disp(TicaCoverageSummary);

if cfg.ica.requireCompleteRunCoverage && ...
        (~all(TicaRunCoverage.PrimaryOK) || ~all(TicaRunCoverage.SensitivityOK))
    failed=TicaRunCoverage(~TicaRunCoverage.PrimaryOK | ...
        ~TicaRunCoverage.SensitivityOK,:);
    writetable(failed,fullfile(cfg.outDir, ...
        'STEP12BICA_ICA_FAILED_RUNS_REQUIRING_REVIEW.csv'));
    error(['STEP12B requires complete ICA/ICLabel coverage before statistics. ' ...
        '%d/%d recordings are still incomplete. See STEP12BICA_ICA_FAILED_RUNS_REQUIRING_REVIEW.csv.'], ...
        height(failed),height(TicaRunCoverage));
end

%% ========================== RETENTION QC ===========================
TretPrimary = extractionRetentionSummary(TchanPrimary,cfg,primaryMode);
TretSens = extractionRetentionSummary(TchanSensitivity,cfg,sensitivityMode);

writetable(TretPrimary,fullfile(cfg.outDir, ...
    'STEP12BICA_QC_Primary_PhaseRetentionSummary.csv'));
writetable(TretSens,fullfile(cfg.outDir, ...
    'STEP12BICA_QC_Sensitivity_PhaseRetentionSummary.csv'));

fprintf('\n================ PRIMARY RETENTION =================\n');
disp(TretPrimary);
fprintf('\n=============== SENSITIVITY RETENTION ==============\n');
disp(TretSens);

%% ======================= PRIMARY ROI TABLE =========================
fprintf('\nBuilding primary non-overlapping scalp ROI features...\n');
Tchan = TchanPrimary;
Tchan.ROI = strings(height(Tchan),1);
for i=1:height(Tchan)
    Tchan.ROI(i) = channelToROI(Tchan.ChannelName(i),cfg.roi);
end

validROI = Tchan.ROI~="other";
if any(~validROI)
    warning('%d primary channel-feature rows could not be mapped to a spectral ROI.', ...
        sum(~validROI));
end

roiKeys = {'Subject','ConditionLabel','PhaseLabel','Band','ROI'};
[G,Troi] = findgroups(Tchan(validROI,roiKeys));
Xroi = Tchan(validROI,:);

Troi.AbsPower = splitapply(@(x) median(x,'omitnan'),Xroi.AbsPower,G);
Troi.LogAbsPower = splitapply(@(x) median(x,'omitnan'),Xroi.LogAbsPower,G);
Troi.RelPower = splitapply(@(x) median(x,'omitnan'),Xroi.RelPower,G);
Troi.NChannels = splitapply(@(x) numel(unique(x)),Xroi.ChannelIndex,G);
Troi.NTrials = splitapply(@(x) max(x),Xroi.NTrials,G);
Troi.WindowStartMs = zeros(height(Troi),1);
Troi.WindowEndMs = arrayfun(@(i) phaseDurationSec(Troi.PhaseLabel(i),cfg,primaryMode)*1000, ...
    (1:height(Troi))');

writetable(Troi,fullfile(cfg.outDir, ...
    'STEP12BICA_PRIMARY_Article1Matched_SubjectROIFeatures_N22.csv'));

%% ================= PRIMARY CONDITION STATISTICS ====================
TchanLong = makeLongFeatureTable(Tchan,'ChannelName',"channel");
TroiLong = makeLongFeatureTable(Troi,'ROI',"roi");

[TchanOmni,TchanPair] = conditionStats(TchanLong,cfg.minSubjectsForStats);
[TroiOmni,TroiPair] = conditionStats(TroiLong,cfg.minSubjectsForStats);

writetable(TchanOmni,fullfile(cfg.outDir, ...
    'STEP12BICA_PRIMARY_Article1Matched_Channel_Omnibus.csv'));
writetable(TchanPair,fullfile(cfg.outDir, ...
    'STEP12BICA_PRIMARY_Article1Matched_Channel_Pairwise.csv'));
writetable(TroiOmni,fullfile(cfg.outDir, ...
    'STEP12BICA_PRIMARY_Article1Matched_ROI_Omnibus.csv'));
writetable(TroiPair,fullfile(cfg.outDir, ...
    'STEP12BICA_PRIMARY_Article1Matched_ROI_Pairwise.csv'));

TphaseCountsPrimary = [phaseCountSummary(TchanOmni,"channel"); ...
                       phaseCountSummary(TroiOmni,"roi")];
writetable(TphaseCountsPrimary,fullfile(cfg.outDir, ...
    'STEP12BICA_PRIMARY_Article1Matched_PhaseEffectCountSummary.csv'));

%% ================= PRIMARY FOCUSED SPECTRAL INDICES ================
TcompPrimary = buildFocusedIndices(Troi);
writetable(TcompPrimary,fullfile(cfg.outDir, ...
    'STEP12BICA_PRIMARY_Article1Matched_FocusedIndices_SubjectConditionPhase.csv'));

% Explicit condition statistics for the focused primary indices, used for
% alpha/gamma ICA robustness decisions.
[TcompPrimaryOmni,TcompPrimaryPair] = conditionStats(TcompPrimary,cfg.minSubjectsForStats);
writetable(TcompPrimaryOmni,fullfile(cfg.outDir, ...
    'STEP12BICA_PRIMARY_FocusedIndices_Omnibus.csv'));
writetable(TcompPrimaryPair,fullfile(cfg.outDir, ...
    'STEP12BICA_PRIMARY_FocusedIndices_Pairwise.csv'));

%% ============== EQUAL-0.6 s SENSITIVITY ROI TABLE ==================
Tsens = TchanSensitivity;
Tsens.ROI = strings(height(Tsens),1);
for i=1:height(Tsens)
    Tsens.ROI(i) = channelToROI(Tsens.ChannelName(i),cfg.roi);
end

validROIs = Tsens.ROI~="other";
roiKeysS = {'Subject','ConditionLabel','PhaseLabel','Band','ROI'};
[Gs,TroiSens] = findgroups(Tsens(validROIs,roiKeysS));
Xs = Tsens(validROIs,:);

TroiSens.AbsPower = splitapply(@(x) median(x,'omitnan'),Xs.AbsPower,Gs);
TroiSens.LogAbsPower = splitapply(@(x) median(x,'omitnan'),Xs.LogAbsPower,Gs);
TroiSens.RelPower = splitapply(@(x) median(x,'omitnan'),Xs.RelPower,Gs);
TroiSens.NChannels = splitapply(@(x) numel(unique(x)),Xs.ChannelIndex,Gs);
TroiSens.NTrials = splitapply(@(x) max(x),Xs.NTrials,Gs);
TroiSens.WindowStartMs = zeros(height(TroiSens),1);
TroiSens.WindowEndMs = repmat(cfg.sensitivityWindowSec*1000,height(TroiSens),1);

writetable(TroiSens,fullfile(cfg.outDir, ...
    'STEP12BICA_EQUAL0600_Equal0600_SubjectROIFeatures_N22.csv'));

TchanSensLong = makeLongFeatureTable(Tsens,'ChannelName',"channel");
TroiSensLong = makeLongFeatureTable(TroiSens,'ROI',"roi");

[TchanSensOmni,TchanSensPair] = conditionStats(TchanSensLong,cfg.minSubjectsForStats);
[TroiSensOmni,TroiSensPair] = conditionStats(TroiSensLong,cfg.minSubjectsForStats);

writetable(TchanSensOmni,fullfile(cfg.outDir, ...
    'STEP12BICA_EQUAL0600_Channel_Omnibus.csv'));
writetable(TchanSensPair,fullfile(cfg.outDir, ...
    'STEP12BICA_EQUAL0600_Equal0600_Channel_Pairwise.csv'));
writetable(TroiSensOmni,fullfile(cfg.outDir, ...
    'STEP12BICA_EQUAL0600_ROI_Omnibus.csv'));
writetable(TroiSensPair,fullfile(cfg.outDir, ...
    'STEP12BICA_EQUAL0600_Equal0600_ROI_Pairwise.csv'));

TphaseCounts = [phaseCountSummary(TchanSensOmni,"channel"); ...
                phaseCountSummary(TroiSensOmni,"roi")];
writetable(TphaseCounts,fullfile(cfg.outDir, ...
    'STEP12BICA_EQUAL0600_Equal0600_PhaseEffectCountSummary.csv'));

%% ============= DIRECT PHASE: EQUAL-0.6 s SPECTRAL ONLY ============
% IMPORTANT: direct phase magnitude comparisons are performed ONLY on the
% equal 0-0.6 s sensitivity branch, not on the unequal primary windows.

TchanMag = conditionEffectMagnitude(TchanSensLong);
TroiMag = conditionEffectMagnitude(TroiSensLong);

[TchanPhaseOmni,TchanPhasePair] = directPhaseStats( ...
    TchanMag,cfg.minSubjectsForStats,false);
[TroiPhaseOmni,TroiPhasePair] = directPhaseStats( ...
    TroiMag,cfg.minSubjectsForStats,false);

writetable(TchanMag,fullfile(cfg.outDir, ...
    'STEP12BICA_EQUAL0600_Channel_ConditionEffectMagnitude.csv'));
writetable(TroiMag,fullfile(cfg.outDir, ...
    'STEP12BICA_EQUAL0600_ROI_ConditionEffectMagnitude.csv'));
writetable(TchanPhaseOmni,fullfile(cfg.outDir, ...
    'STEP12BICA_EQUAL0600_Channel_DirectPhase_Omnibus.csv'));
writetable(TchanPhasePair,fullfile(cfg.outDir, ...
    'STEP12BICA_EQUAL0600_Channel_DirectPhase_Pairwise.csv'));
writetable(TroiPhaseOmni,fullfile(cfg.outDir, ...
    'STEP12BICA_EQUAL0600_ROI_DirectPhase_Omnibus.csv'));
writetable(TroiPhasePair,fullfile(cfg.outDir, ...
    'STEP12BICA_EQUAL0600_ROI_DirectPhase_Pairwise.csv'));

%% ============ FOCUSED INDICES: EQUAL-0.6 s DIRECT PHASE ============
Tcomp = buildFocusedIndices(TroiSens);
TcompMag = conditionEffectMagnitude(Tcomp);

[TcompPhaseOmni,TcompPhasePair] = directPhaseStats( ...
    TcompMag,cfg.minSubjectsForStats,true);

writetable(Tcomp,fullfile(cfg.outDir, ...
    'STEP12BICA_EQUAL0600_FocusedIndices_SubjectConditionPhase.csv'));
writetable(TcompMag,fullfile(cfg.outDir, ...
    'STEP12BICA_EQUAL0600_FocusedIndices_ConditionEffectMagnitude.csv'));
writetable(TcompPhaseOmni,fullfile(cfg.outDir, ...
    'STEP12BICA_EQUAL0600_FocusedIndices_DirectPhase_Omnibus.csv'));
writetable(TcompPhasePair,fullfile(cfg.outDir, ...
    'STEP12BICA_EQUAL0600_FocusedIndices_DirectPhase_Pairwise.csv'));

Tdir = buildDirectionalContrasts(Tcomp);
[TdirPhaseOmni,TdirPhasePair] = directPhaseStats( ...
    Tdir,cfg.minSubjectsForStats,true);

writetable(Tdir,fullfile(cfg.outDir, ...
    'STEP12BICA_EQUAL0600_FocusedIndices_DirectionalContrasts.csv'));
writetable(TdirPhaseOmni,fullfile(cfg.outDir, ...
