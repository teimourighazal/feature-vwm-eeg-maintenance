function [Xclean,labels,fs,info] = readAndICAcleanRawEEG(rawPath,cfg)
% STEP12B complete-run recovery.
%   1) Read + documented 0.5-45-Hz preprocessing.
%   2) Reuse a STEP12B model if already available.
%   3) Otherwise reuse the ICA decomposition from STEP12 when possible.
%   4) Fit ICA only when no reusable decomposition exists, saving the
%      decomposition BEFORE ICLabel so an ICLabel failure never loses ICA.
%   5) Reclassify every run uniformly with ICLabel 'lite' on a deterministic
%      centered segment. Only Eye/Muscle >= 0.90 are removed.
%
% ICA is fitted on the full continuous recording. The shorter segment is
% used ONLY to classify the already-fitted independent components.

[Xraw,labels,fs]=readRawEEG(rawPath,cfg.fsDefault,cfg.maxChannels);
Xmain=applyDocumentedPreprocessing(Xraw,fs);

token=safePathToken(rawPath);
modelFile=fullfile(cfg.ica.modelDir,[token '_ICAmodel.mat']);
decompFile=fullfile(cfg.ica.decompDir,[token '_ICAdecomp.mat']);
oldModelFile=fullfile(cfg.ica.previousStep12ModelDir,[token '_ICAmodel.mat']);

model=[];
modelSource="";

% First reuse a completed STEP12B model.
if exist(modelFile,'file')==2
    try
        S=load(modelFile,'model');
        if isfield(S,'model') && isValidRecoveryModel(S.model,size(Xmain,2),fs,cfg)
            model=S.model;
            modelSource="cached_STEP12B_model";
        end
    catch
        model=[];
    end
end

if isempty(model)
    decomp=[];
    decompSource="";

    % Reuse a STEP12B decomposition if a previous recovery attempt saved it.
    if exist(decompFile,'file')==2
        try
            S=load(decompFile,'decomp');
            if isfield(S,'decomp') && isValidDecomposition(S.decomp,size(Xmain,2),fs)
                decomp=S.decomp;
                decompSource="cached_STEP12B_decomposition";
            end
        catch
            decomp=[];
        end
    end

    % Reuse the original STEP12 decomposition from any successful model.
    if isempty(decomp) && exist(oldModelFile,'file')==2
        try
            S=load(oldModelFile,'model');
            if isfield(S,'model') && isValidDecomposition(S.model,size(Xmain,2),fs)
                decomp=decompositionFromModel(S.model);
                decompSource="reused_STEP12_decomposition";
                save(decompFile,'decomp','-v7.3');
            end
        catch
            decomp=[];
        end
    end

    % Only the runs without a reusable decomposition require expensive ICA.
    if isempty(decomp)
        decomp=fitICADecompositionOnly(Xmain,fs,cfg,rawPath);
        decompSource="new_STEP12B_ICA_fit";
        % Critical recovery feature: save ICA BEFORE ICLabel.
        save(decompFile,'decomp','-v7.3');
    end

    model=classifyDecompositionWithICLabelLite( ...
        Xmain,labels,fs,cfg,rawPath,decomp,decompSource);
    save(modelFile,'model','-v7.3');
    modelSource=string(model.DecompositionSource) + "+" + ...
        string(model.ICLabelVersion) + "_" + ...
        string(round(model.ClassificationSegmentSec)) + "s";
end

% Apply decomposition/rejection to the documented 0.5-45-Hz analysis data.
Sact=model.W*double(Xmain)';
if ~isempty(model.rejectedComponents)
    Sact(model.rejectedComponents,:)=0;
end
Xclean=(model.A*Sact)';
Xclean=Xclean-mean(Xclean,2,'omitnan');

info=struct();
info.Status="ok";
if model.RejectFraction>cfg.ica.maxRejectFractionWarning
    info.Status="ok_high_reject_fraction_warning";
end
info.ModelSource=modelSource;
info.Rank=model.rankEst;
info.NComponents=size(model.W,1);
info.NRejected=numel(model.rejectedComponents);
info.NEyeRejected=numel(model.eyeRejectedComponents);
info.NMuscleRejected=numel(model.muscleRejectedComponents);
info.MaxEyeProbability=max(model.eyeProb,[],'omitnan');
info.MaxMuscleProbability=max(model.muscleProb,[],'omitnan');
info.RejectFraction=model.RejectFraction;
end

function tf = isValidRecoveryModel(model,nChan,fs,cfg)
tf=isValidDecomposition(model,nChan,fs) && ...
    isfield(model,'eyeThreshold') && ...
    abs(model.eyeThreshold-cfg.ica.eyeThreshold)<1e-12 && ...
    isfield(model,'muscleThreshold') && ...
    abs(model.muscleThreshold-cfg.ica.muscleThreshold)<1e-12 && ...
    isfield(model,'fitHighpassHz') && ...
    abs(model.fitHighpassHz-cfg.ica.fitHighpassHz)<1e-12 && ...
    isfield(model,'ICLabelVersion') && ...
    strcmpi(char(string(model.ICLabelVersion)),cfg.ica.classifierVersion) && ...
    isfield(model,'rejectedComponents');
end

function tf = isValidDecomposition(d,nChan,fs)
tf=isstruct(d) && isfield(d,'W') && isfield(d,'A') && ...
    isfield(d,'weights') && isfield(d,'sphere') && ...
    isfield(d,'rankEst') && isfield(d,'fs') && ...
    size(d.W,2)==nChan && size(d.A,1)==nChan && ...
    abs(double(d.fs)-double(fs))<1e-6 && ...
    all(isfinite(d.W(:))) && all(isfinite(d.A(:)));
end

function decomp = decompositionFromModel(model)
decomp=struct();
decomp.W=model.W;
decomp.A=model.A;
decomp.weights=model.weights;
decomp.sphere=model.sphere;
decomp.fs=model.fs;
decomp.rankEst=model.rankEst;
if isfield(model,'fitHighpassHz')
    decomp.fitHighpassHz=model.fitHighpassHz;
end
end

function decomp = fitICADecompositionOnly(Xmain,fs,cfg,rawPath)
% Fit extended Infomax ICA on the FULL continuous 1-Hz-high-pass copy.

Xfit=double(Xmain);
if cfg.ica.fitHighpassHz>0
    [bh,ah]=butter(2,cfg.ica.fitHighpassHz/(fs/2),'high');
    Xfit=filtfilt(bh,ah,Xfit);
end

rankEst=estimateICARank(Xfit,fs);
if rankEst<2
    error('Estimated ICA rank is %d for %s.',rankEst,char(rawPath));
end

fprintf('  ICA fit (new recovery): rank=%d | samples=%d | channels=%d\n', ...
    rankEst,size(Xfit,1),size(Xfit,2));

try
    [weights,sphere]=runica(Xfit','extended',1,'pca',rankEst);
catch ME
    error('runica failed for %s: %s',char(rawPath),ME.message);
end

W=weights*sphere;
A=pinv(W);

decomp=struct();
decomp.W=W;
decomp.A=A;
decomp.weights=weights;
decomp.sphere=sphere;
decomp.fs=fs;
decomp.rankEst=rankEst;
decomp.fitHighpassHz=cfg.ica.fitHighpassHz;
decomp.rawPath=string(rawPath);
end

function model = classifyDecompositionWithICLabelLite( ...
    Xmain,labels,fs,cfg,rawPath,decomp,decompSource)
% Classify an already-fitted ICA decomposition uniformly with ICLabel Lite.
% The official Lite model retains IC topography + PSD features and omits the
% autocorrelation feature. This is used for ALL 66 recordings in STEP12B.

Xfit=double(Xmain);
if cfg.ica.fitHighpassHz>0
    [bh,ah]=butter(2,cfg.ica.fitHighpassHz/(fs/2),'high');
    Xfit=filtfilt(bh,ah,Xfit);
end

segmentCandidates=unique(cfg.ica.classificationFallbackSec,'stable');
lastME=[];
EEG=[];
usedSec=NaN;

for k=1:numel(segmentCandidates)
    requestedSec=segmentCandidates(k);
    nClass=min(size(Xfit,1),max(round(10*fs),round(requestedSec*fs)));
    s0=floor((size(Xfit,1)-nClass)/2)+1;
    s1=s0+nClass-1;
    Xclass=Xfit(s0:s1,:);

    EEG=eeg_emptyset;
    EEG.data=single(Xclass');
    EEG.srate=fs;
    EEG.nbchan=size(Xclass,2);
    EEG.pnts=size(Xclass,1);
    EEG.trials=1;
    EEG.xmin=0;
    EEG.xmax=(EEG.pnts-1)/fs;
    EEG.times=(0:EEG.pnts-1)/fs*1000;
    EEG.setname='STEP12B_ICA_recovery';
    EEG.icaweights=decomp.weights;
    EEG.icasphere=decomp.sphere;
    EEG.icawinv=decomp.A;
    EEG.icachansind=1:EEG.nbchan;
    EEG.icaact=[];

    EEG.chanlocs=repmat(struct('labels',''),1,EEG.nbchan);
    for ch=1:EEG.nbchan
        EEG.chanlocs(ch).labels=char(string(labels{ch}));
    end

    try
        EEG=pop_chanedit(EEG,'lookup',cfg.ica.lookupFile);
        EEG=eeg_checkset(EEG);
        EEG=iclabel(EEG,cfg.ica.classifierVersion);
        usedSec=(s1-s0+1)/fs;
        break;
    catch ME
        lastME=ME;
        EEG=[];
        fprintf('  ICLabel %s failed on %.0f-s segment; retrying shorter segment.\n', ...
            cfg.ica.classifierVersion,requestedSec);
    end
end

if isempty(EEG)
    if isempty(lastME)
        error('ICLabel recovery failed for %s.',char(rawPath));
    else
        error('ICLabel %s failed for %s after all segment retries: %s', ...
            cfg.ica.classifierVersion,char(rawPath),lastME.message);
    end
end

probs=EEG.etc.ic_classification.ICLabel.classifications;
classes=string(EEG.etc.ic_classification.ICLabel.classes);
eyeCol=find(strcmpi(classes,'Eye'),1);
muscleCol=find(strcmpi(classes,'Muscle'),1);
if isempty(eyeCol) || isempty(muscleCol)
    error('ICLabel output did not contain Eye and Muscle classes.');
end

eyeProb=probs(:,eyeCol);
muscleProb=probs(:,muscleCol);
eyeReject=find(eyeProb>=cfg.ica.eyeThreshold);
muscleReject=find(muscleProb>=cfg.ica.muscleThreshold);
rejected=unique([eyeReject(:);muscleReject(:)]);

rejectFraction=numel(rejected)/size(decomp.W,1);
if rejectFraction>cfg.ica.maxRejectFractionWarning
    warning(['ICA rejected %.1f%% of components in %s. Thresholds were NOT ' ...
        'changed; this run is flagged for QC review.'], ...
        100*rejectFraction,char(rawPath));
end

model=decomp;
model.labels=string(labels(:));
model.iclabelClasses=classes;
model.iclabelProbabilities=probs;
model.eyeProb=eyeProb;
model.muscleProb=muscleProb;
model.eyeRejectedComponents=eyeReject(:)';
model.muscleRejectedComponents=muscleReject(:)';
model.rejectedComponents=rejected(:)';
model.RejectFraction=rejectFraction;
model.eyeThreshold=cfg.ica.eyeThreshold;
model.muscleThreshold=cfg.ica.muscleThreshold;
model.fitHighpassHz=cfg.ica.fitHighpassHz;
model.rawPath=string(rawPath);
model.ICLabelVersion=string(cfg.ica.classifierVersion);
model.ClassificationSegmentSec=usedSec;
model.DecompositionSource=string(decompSource);

% Component-level QC; probabilities are mapped by class name rather than
% assuming a hard-coded column order.
nComp=size(probs,1);
Tqc=table(repmat(string(rawPath),nComp,1),(1:nComp)', ...
    repmat(string(cfg.ica.classifierVersion),nComp,1), ...
    repmat(usedSec,nComp,1), ...
