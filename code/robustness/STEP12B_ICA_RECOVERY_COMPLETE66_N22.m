function [O,P] = directPhaseStats(T,minN,globalFamily)
if isempty(T); O=table();P=table();return;end
keys=unique(T(:,{'EEGMetric','Band','FeatureName','AnalysisLevel'}), ...
    'rows','stable');
phases=["stimulus","maintenance","retrieval"];
orows=cell(0,14);
prows=cell(0,12);

for i=1:height(keys)
    S=T(T.EEGMetric==keys.EEGMetric(i)&T.Band==keys.Band(i)& ...
        T.FeatureName==keys.FeatureName(i)& ...
        T.AnalysisLevel==keys.AnalysisLevel(i),:);
    subj=unique(S.Subject,'stable');
    X=nan(numel(subj),3);
    for is=1:numel(subj)
        for ip=1:3
            x=S.EffectMagnitude(S.Subject==subj(is)& ...
                S.PhaseLabel==phases(ip));
            if any(isfinite(x)); X(is,ip)=median(x,'omitnan'); end
        end
    end
    ok=all(isfinite(X),2);
    X=X(ok,:); subj=subj(ok);
    if size(X,1)<minN; continue; end

    [pF,chi2,W]=friedmanStats(X);
    med=median(X,1,'omitnan');
    dom=med(2)>med(1)&&med(2)>med(3);

    orows(end+1,:)={keys.AnalysisLevel(i),keys.EEGMetric(i), ...
        keys.Band(i),keys.FeatureName(i),size(X,1), ...
        med(1),med(2),med(3),pF,chi2,W,dom, ...
        strjoin(subj,'|'),false}; %#ok<AGROW>

    comp={2,1,"maintenance_vs_stimulus"; ...
          2,3,"maintenance_vs_retrieval"};
    for k=1:2
        d=X(:,comp{k,1})-X(:,comp{k,2});
        try
            p=signrank(X(:,comp{k,1}),X(:,comp{k,2}), ...
                'tail','right');
        catch
            p=NaN;
        end
        prows(end+1,:)={keys.AnalysisLevel(i),keys.EEGMetric(i), ...
            keys.Band(i),keys.FeatureName(i),string(comp{k,3}), ...
            size(X,1),median(X(:,comp{k,1}),'omitnan'), ...
            median(X(:,comp{k,2}),'omitnan'),median(d,'omitnan'), ...
            p,mean(d>0,'omitnan'),strjoin(subj,'|')}; %#ok<AGROW>
    end
end

if isempty(orows)
    O=table();
else
    O=cell2table(orows,'VariableNames', ...
        {'AnalysisLevel','EEGMetric','Band','FeatureName','NSubjects', ...
         'MedianEffect_Stimulus','MedianEffect_Maintenance', ...
         'MedianEffect_Retrieval','p_PhaseFriedman','ChiSquare', ...
         'KendallW','MaintenanceDominant','SubjectsUsed','StrongSupport'});
    O=standardizeOutputTable(O);
    O.q_PhaseFDR=nan(height(O),1);
end

if isempty(prows)
    P=table();
else
    P=cell2table(prows,'VariableNames', ...
        {'AnalysisLevel','EEGMetric','Band','FeatureName','Contrast', ...
         'NSubjects','Median_Maintenance','Median_Comparator', ...
         'MedianDifference','p_OneSidedSignrank', ...
         'Proportion_MaintenanceGreater','SubjectsUsed'});
    P=standardizeOutputTable(P);
    P.q_FDR=nan(height(P),1);
end

if isempty(O); return; end

if globalFamily
    O.q_PhaseFDR=bhFDR(O.p_PhaseFriedman);
    if ~isempty(P); P.q_FDR=bhFDR(P.p_OneSidedSignrank); end
else
    metrics=unique(O.EEGMetric,'stable');
    for im=1:numel(metrics)
        idx=O.EEGMetric==metrics(im);
        O.q_PhaseFDR(idx)=bhFDR(O.p_PhaseFriedman(idx));
        if ~isempty(P)
            idxp=P.EEGMetric==metrics(im);
            P.q_FDR(idxp)=bhFDR(P.p_OneSidedSignrank(idxp));
        end
    end
end

if ~isempty(P)
    P.SignificantFDR=P.q_FDR<0.05;
    for i=1:height(O)
        idx=P.EEGMetric==O.EEGMetric(i)&P.Band==O.Band(i)& ...
            P.FeatureName==O.FeatureName(i)& ...
            P.AnalysisLevel==O.AnalysisLevel(i);
        Q=P(idx,:);
        q1=Q.q_FDR(Q.Contrast=="maintenance_vs_stimulus");
        q2=Q.q_FDR(Q.Contrast=="maintenance_vs_retrieval");
        both=~isempty(q1)&&~isempty(q2)&&all(q1<0.05)&&all(q2<0.05);
        O.StrongSupport(i)=O.q_PhaseFDR(i)<0.05&& ...
            O.MaintenanceDominant(i)&&both;
    end
end
end

function [p,chi2,W] = friedmanStats(X)
p=NaN;chi2=NaN;W=NaN;
try
    [p,tbl]=friedman(X,1,'off');
    chi2=tbl{2,5};
    W=chi2/(size(X,1)*(size(X,2)-1));
catch
    n=size(X,1); k=size(X,2);
    R=zeros(size(X));
    for i=1:n; R(i,:)=tiedrank(X(i,:)); end
    Rj=sum(R,1);
    chi2=(12/(n*k*(k+1)))*sum(Rj.^2)-3*n*(k+1);
    p=1-chi2cdf(chi2,k-1);
    W=chi2/(n*(k-1));
end
end

function q = bhFDR(p)
p=double(p(:));q=nan(size(p));
ok=isfinite(p);pv=p(ok);
if isempty(pv);return;end
[ps,ord]=sort(pv);
m=numel(ps);
qs=ps.*m./(1:m)';
qs=flipud(cummin(flipud(qs)));
qs(qs>1)=1;
z=nan(m,1);z(ord)=qs;q(ok)=z;
end

