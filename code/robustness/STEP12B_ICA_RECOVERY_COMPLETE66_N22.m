function [M,rawMap] = repairRawPaths(M,rawRoot)
% Repair stale absolute paths after the IPM folder has been moved.
%
% Priority:
%   1) retain an existing path;
%   2) preserve the old relative path below IPM/Subjects;
%   3) match the exact old filename inside the new Subjects root;
%   4) propagate a successfully matched path to other rows from the same
%      Subject x Run cell.
%
% This is essential because subject IDs such as s1 do not correspond to the
% participant-name folder names in the raw archive.

rawMap=buildRawFileMap(rawRoot);
if isempty(rawMap)
    error(['No MAT or EDF recording files were found under:\n%s\n' ...
        'The selected folder must be the Subjects folder containing ' ...
        'participant-name subfolders and task MAT files.'],rawRoot);
end

M.RawPathMatchMode=repmat("",height(M),1);
M.OriginalRawEEGPath=string(M.RawEEGPath);

for i=1:height(M)
    oldPath=strtrim(string(M.RawEEGPath(i)));

    if strlength(oldPath)>0 && exist(oldPath,'file')==2
        M.RawPathMatchMode(i)="existing_path";
        continue;
    end

    [newPath,mode]=relocateRawPath(oldPath,rawRoot,rawMap);
    if strlength(newPath)>0
        M.RawEEGPath(i)=newPath;
        M.RawPathMatchMode(i)=mode;
    else
        M.RawEEGPath(i)="";
        M.RawPathMatchMode(i)="unresolved_first_pass";
    end
end

% Second pass: propagate within Subject x Run after at least one row from
% that recording has been matched by its old filename.
keys=unique(M(:,{'Subject','Run'}),'rows','stable');
for k=1:height(keys)
    idx=M.Subject==keys.Subject(k) & M.Run==keys.Run(k);
    resolved=unique(M.RawEEGPath(idx & strlength(M.RawEEGPath)>0));
    resolved=resolved(strlength(resolved)>0);

    if numel(resolved)==1
        fill=idx & strlength(M.RawEEGPath)==0;
        M.RawEEGPath(fill)=resolved(1);
        M.RawPathMatchMode(fill)="propagated_subject_run";
    end
end

nResolved=sum(strlength(M.RawEEGPath)>0);
fprintf('\nRaw path repair: %d/%d trial-phase rows resolved.\n', ...
    nResolved,height(M));

modes=unique(M.RawPathMatchMode,'stable');
for i=1:numel(modes)
    fprintf('  %-32s %d\n',modes(i),sum(M.RawPathMatchMode==modes(i)));
end

if nResolved==0
    error(['The MAT files were found, but none could be linked to the ' ...
        'stale paths in the merged table. Inspect STEP12BICA_RawFileInventory.csv.']);
end
end

function [newPath,mode] = relocateRawPath(oldPath,rawRoot,rawMap)
newPath="";
mode="";

if strlength(oldPath)==0 || ismissing(oldPath)
    return;
end

oldChar=char(oldPath);
oldNorm=strrep(oldChar,'\','/');
oldLower=lower(oldNorm);

% A) Preserve the relative path below IPM/Subjects.
marker='ipm/subjects/';
pos=strfind(oldLower,marker);
if ~isempty(pos)
    suffix=oldNorm(pos(end)+length(marker):end);
    parts=strsplit(suffix,'/');
    candidate=rawRoot;
    for j=1:numel(parts)
        if ~isempty(parts{j})
            candidate=fullfile(candidate,parts{j});
        end
    end
    if exist(candidate,'file')==2
        newPath=string(candidate);
        mode="relative_path_below_subjects";
        return;
    end
end

% B) Exact filename match anywhere below the new Subjects root.
[oldParent,name,ext]=fileparts(oldChar);
target=lower(string([name ext]));
idx=lower(rawMap.FileName)==target;

if any(idx)
    C=rawMap(idx,:);

    % Prefer the same parent-folder name when duplicate filenames exist.
    [~,oldParentName]=fileparts(oldParent);
    sameParent=strcmpi(C.ParentFolder,string(oldParentName));
    if any(sameParent)
        C=C(sameParent,:);
    end

    [~,ord]=sort(C.CandidateScore,'descend');
    C=C(ord,:);

    for j=1:height(C)
        if exist(C.RawEEGPath(j),'file')==2
            newPath=C.RawEEGPath(j);
            mode="exact_filename";
            return;
        end
    end
end

% C) Same filename stem, allowing extension differences.
idx=lower(rawMap.BaseName)==lower(string(name));
if any(idx)
    C=rawMap(idx,:);
    [~,ord]=sort(C.CandidateScore,'descend');
    C=C(ord,:);
    newPath=C.RawEEGPath(1);
    mode="filename_stem";
end
end

function R = buildRawFileMap(root)
patterns={'*.mat','*.MAT','*.edf','*.EDF'};
files={};

for p=1:numel(patterns)
    files=[files;recursiveFiles(root,patterns{p})]; %#ok<AGROW>
end
files=unique(files,'stable');

rows=cell(0,12);
for i=1:numel(files)
    f=files{i};
    [parent,base,ext]=fileparts(f);
    [~,parentName]=fileparts(parent);
    b=lower(string(base));
    e=lower(string(ext));

    isWorkspace=contains(b,'workspace');
    isRest=isRestingFilename(b);
    isDerived=contains(lower(string(f)), ...
        ["eeg_analysis_advanced","complete_analysis","document", ...
         "patient_","list_","results","output"]);

    score=0;
    if e==".mat"; score=score+4; end
    if e==".edf"; score=score+5; end
    if contains(b,'filtered'); score=score+3; end
    if ~isempty(regexp(char(b),'([0-9]{1,2})$','once'))
        score=score+3;
    end
    if isWorkspace; score=score-25; end
    if isRest; score=score-50; end
    if isDerived; score=score-8; end

    [eegLike,bestVar,bestSize,inspectNote]=inspectRawCandidate(f);
    if eegLike; score=score+40; else; score=score-15; end

    rows(end+1,:)={string(f),string([base ext]),string(base), ...
        string(ext),string(parentName),score,isWorkspace,isRest, ...
        isDerived,eegLike,bestVar,bestSize+"|"+inspectNote}; %#ok<AGROW>
end

if isempty(rows)
    R=table();
    return;
end

R=cell2table(rows,'VariableNames', ...
    {'RawEEGPath','FileName','BaseName','Extension','ParentFolder', ...
     'CandidateScore','IsWorkspace','IsRestingLike','IsDerivedLike', ...
     'EEGLike','BestVariable','Inspection'});
R=standardizeOutputTable(R);

[~,ia]=unique(R.RawEEGPath,'stable');
R=R(ia,:);
R=sortrows(R,{'CandidateScore','RawEEGPath'}, ...
    {'descend','ascend'});

try
    writetable(R,fullfile(root,'STEP12BICA_RawFileInventory.csv'));
catch
end
end

function tf = isRestingFilename(b)
tokens=["rest","resting","eyeopen","eye_open","eye-open", ...
    "eye close","eyeclose","eye_close","eye-close"];
tf=false;
for k=1:numel(tokens)
    if contains(b,tokens(k))
        tf=true;
        return;
    end
end
if ~isempty(regexp(char(b),'(^|[_\-\s])eo($|[_\-\s])','once')) || ...
   ~isempty(regexp(char(b),'(^|[_\-\s])ec($|[_\-\s])','once'))
    tf=true;
end
end

function [tf,bestVar,bestSize,note] = inspectRawCandidate(fpath)
tf=false;
bestVar="";
bestSize="";
note="not_inspected";

[~,~,ext]=fileparts(fpath);
if strcmpi(ext,'.edf')
    tf=true;
    bestVar="EDF";
    bestSize="unknown";
    note="edf_candidate";
    return;
end

if ~strcmpi(ext,'.mat')
    return;
end

try
    info=whos('-file',fpath);
catch ME
    note="whos_failed:"+string(ME.message);
    return;
end

bestScore=-Inf;
for i=1:numel(info)
    sz=double(info(i).size);
    % Some unusual MAT variables can return empty or scalar size metadata.
    % Convert every case to a safe two-element size vector.
    if isempty(sz)
        sz=[0 0];
    elseif isscalar(sz)
        sz=[sz 1];
    else
        sz=sz(1:2);
    end
    a=sz(1); b=sz(2);
    small=min(a,b); large=max(a,b);
    nm=lower(string(info(i).name));
    cls=lower(string(info(i).class));
    score=-Inf;

    if any(cls==["double","single","int16","int32","uint16", ...
            "uint32","logical"])
        if small>=16 && small<=128 && large>=1000
            score=100+log10(max(large,1))*5;
            if any(small==[64 65 66]); score=score+30; end
            if contains(nm,["eeg","data","signal","filtered","x"])
                score=score+15;
            end
        end
    elseif any(cls==["table","timetable"])
        if b>=16 && b<=128 && a>=1000
            score=90+log10(max(a,1))*5;
            if contains(nm,["eeg","data","signal"])
                score=score+15;
            end
        end
    elseif cls=="struct" && contains(nm,["eeg","data","signal"])
        score=40;
    end

    if score>bestScore
        bestScore=score;
        bestVar=string(info(i).name);
        bestSize=string(a)+"x"+string(b);
    end
end

tf=isfinite(bestScore) && bestScore>=40;
if tf
    note="eeg_like_variable_found";
else
    note="no_obvious_eeg_matrix";
end
end

