function X = applyDocumentedPreprocessing(X,fs)
if exist('butter','file')~=2 || exist('filtfilt','file')~=2
    error(['Signal Processing Toolbox functions butter/filtfilt are ' ...
        'required for documented_preprocessing mode.']);
end

X=double(X);
for ch=1:size(X,2)
    bad=~isfinite(X(:,ch));
    if any(bad)
        good=X(~bad,ch);
        if isempty(good)
            X(:,ch)=0;
        else
            X(bad,ch)=median(good);
        end
    end
end

% Fourth-order 0.5-45 Hz zero-phase Butterworth band-pass.
[b,a]=butter(4,[0.5 45]/(fs/2),'bandpass');
X=filtfilt(b,a,X);

% 50-Hz notch implemented as a narrow 49-51 Hz stop band.
if fs/2>51
    [bn,an]=butter(2,[49 51]/(fs/2),'stop');
    X=filtfilt(bn,an,X);
end

% Average reference across retained channels.
X=X-mean(X,2,'omitnan');
end

