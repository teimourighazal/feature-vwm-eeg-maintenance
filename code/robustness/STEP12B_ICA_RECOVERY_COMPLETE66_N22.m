function [Tsubj,Tlog] = extractSubjectSpectralFeaturesFinal(M,cfg,branch)
groups=unique(M(:,{'Subject','ConditionLabel','PhaseLabel'}), ...
    'rows','stable');
nG=height(groups);

absCells=cell(nG,1);
relCells=cell(nG,1);
for g=1:nG
    absCells{g}=cell(0,1);
    relCells{g}=cell(0,1);
end

labelsByGroup=cell(nG,1);
trialCounts=zeros(nG,1);
durationByGroup=nan(nG,1);
logRows=cell(0,16);

rawFiles=unique(M.RawEEGPath,'stable');
for ifile=1:numel(rawFiles)
    rawPath=rawFiles(ifile);
    fprintf('Reading %d/%d: %s\n',ifile,numel(rawFiles),rawPath);

    try
        [X,labels,fs,icaInfo]=readAndICAcleanRawEEG(rawPath,cfg);

    catch ME
        warning('Read/preprocessing/ICA failed: %s',ME.message);
        logRows(end+1,:)={rawPath,false,string(ME.message), ...
            NaN,NaN,branch,0,"failed",NaN,NaN,NaN,NaN,NaN,NaN,NaN,NaN}; %#ok<AGROW>
        continue;
    end

    rows=M(M.RawEEGPath==rawPath,:);
    nExtracted=0;

    for r=1:height(rows)
        onset=round(rows.PhaseStartSample(r));
        durationSec=phaseDurationSec(rows.PhaseLabel(r),cfg,branch);
        nEpoch=round(durationSec*fs);

        e0=onset;
        e1=onset+nEpoch-1;

        if ~isfinite(onset) || e0<1 || e1>size(X,1) || e1<e0
            continue;
        end

        % IMPORTANT: no pre-event baseline interval is included in spectral
        % feature calculation. The event-locked post-onset segment alone is
        % used, matching the revised Article1 analysis description.
        seg=double(X(e0:e1,:));

        % Demean and linearly detrend each channel within the analyzed segment.
        for ch=1:size(seg,2)
            x=seg(:,ch);
            good=isfinite(x);
            if sum(good)<max(10,round(0.25*fs))
                seg(:,ch)=NaN;
                continue;
            end

            if any(~good)
                x(~good)=median(x(good));
            end

            x=x-mean(x,'omitnan');
            x=detrend(x,'linear');
            seg(:,ch)=x;
        end

        if cfg.useHamming
            seg=seg.*hammingLocal(size(seg,1));
        end

        [bp,rp]=bandPowerOriginalStyle(seg,fs,cfg.bandRanges);
        if ~any(isfinite(bp(:))); continue; end

        g=find(groups.Subject==rows.Subject(r) & ...
               groups.ConditionLabel==rows.ConditionLabel(r) & ...
               groups.PhaseLabel==rows.PhaseLabel(r),1);
        if isempty(g); continue; end

        absCells{g}{end+1,1}=bp; %#ok<AGROW>
        relCells{g}{end+1,1}=rp; %#ok<AGROW>
        labelsByGroup{g}=labels;
        trialCounts(g)=trialCounts(g)+1;
        durationByGroup(g)=durationSec;
        nExtracted=nExtracted+1;
    end

    logRows(end+1,:)={rawPath,true,string(icaInfo.Status),size(X,1), ...
        size(X,2),branch,nExtracted,string(icaInfo.ModelSource), ...
        icaInfo.Rank,icaInfo.NComponents,icaInfo.NRejected, ...
        icaInfo.NEyeRejected,icaInfo.NMuscleRejected, ...
        icaInfo.MaxEyeProbability,icaInfo.MaxMuscleProbability, ...
        icaInfo.RejectFraction}; %#ok<AGROW>
end

rowsOut=cell(0,14);
for g=1:nG
    if isempty(absCells{g}); continue; end

    A=cat(3,absCells{g}{:});
    R=cat(3,relCells{g}{:});
    medA=median(A,3,'omitnan');
    medR=median(R,3,'omitnan');

    % Natural log, consistent with the Article2 manuscript wording.
    medL=median(log(A+cfg.logOffset),3,'omitnan');

    labels=labelsByGroup{g};
    if isempty(labels)
        labels=default64Labels(size(medA,1));
    end

    for ch=1:size(medA,1)
        for ib=1:numel(cfg.bandNames)
            rowsOut(end+1,:)={groups.Subject(g), ...
                groups.ConditionLabel(g),groups.PhaseLabel(g), ...
                cfg.bandNames(ib),ch,string(labels{ch}), ...
                medA(ch,ib),medL(ch,ib),medR(ch,ib), ...
                trialCounts(g),branch,0,durationByGroup(g)*1000, ...
                durationByGroup(g)*1000}; %#ok<AGROW>
        end
    end
end

Tsubj=cell2table(rowsOut,'VariableNames', ...
    {'Subject','ConditionLabel','PhaseLabel','Band', ...
     'ChannelIndex','ChannelName','AbsPower','LogAbsPower', ...
     'RelPower','NTrials','ExtractionMode','WindowStartMs','WindowEndMs','EpochDurationMs'});

% WindowEndMs and EpochDurationMs are identical because WindowStartMs=0.
if ~isempty(Tsubj)
    Tsubj.WindowEndMs=Tsubj.EpochDurationMs;
end
Tsubj=standardizeOutputTable(Tsubj);

if isempty(logRows)
    Tlog=table();
else
    Tlog=cell2table(logRows,'VariableNames', ...
        {'RawEEGPath','ReadOK','Status','NSamples','NChannels', ...
         'ExtractionMode','NExtractedTrialPhases','ICA_ModelSource', ...
         'ICA_Rank','ICA_NComponents','ICA_NRejected','ICA_NEyeRejected', ...
         'ICA_NMuscleRejected','ICA_MaxEyeProbability', ...
         'ICA_MaxMuscleProbability','ICA_RejectFraction'});
    Tlog=standardizeOutputTable(Tlog);
end
end

function sec = phaseDurationSec(phase,cfg,branch)
phase=normalizePhase(phase);
phase=phase(1);

if branch=="equal0600_sensitivity"
    sec=cfg.sensitivityWindowSec;
    return;
end

switch char(phase)
    case 'stimulus'
        sec=cfg.primaryWindowSec.stimulus;
    case 'maintenance'
        sec=cfg.primaryWindowSec.maintenance;
    case 'retrieval'
        sec=cfg.primaryWindowSec.retrieval;
    otherwise
        sec=NaN;
end
end

function T = extractionRetentionSummary(Tchan,cfg,branch)
phases=["stimulus","maintenance","retrieval"];
rows=cell(0,5);

for i=1:numel(phases)
    S=Tchan(Tchan.PhaseLabel==phases(i),:);
    if isempty(S)
        nSubj=0;
        nCells=0;
        medianTrials=NaN;
    else
        nSubj=numel(unique(S.Subject));
        U=unique(S(:,{'Subject','ConditionLabel','PhaseLabel','NTrials'}),'rows');
        nCells=height(U);
        medianTrials=median(U.NTrials,'omitnan');
    end

    dur=phaseDurationSec(phases(i),cfg,branch);
    rows(end+1,:)={phases(i),nSubj,nCells,medianTrials,dur*1000}; %#ok<AGROW>
end

T=cell2table(rows,'VariableNames', ...
    {'PhaseLabel','NSubjects','NSubjectConditionCells','MedianTrialsPerCell','WindowDurationMs'});
end

function [X,labels,fs] = readRawEEG(rawPath,fsDefault,maxChannels)
rawPath=char(rawPath);
if exist(rawPath,'file')~=2
    error('File not found: %s',rawPath);
end

[~,~,ext]=fileparts(rawPath);

if strcmpi(ext,'.edf')
    [X,labels,fs]=readEDFEEG(rawPath,fsDefault);
elseif strcmpi(ext,'.mat')
    [X,labels,fs]=readMATEEG(rawPath,fsDefault);
else
    error('Unsupported raw EEG extension: %s',ext);
end

if isempty(X) || ~isnumeric(X) || ndims(X)~=2
    error('No usable two-dimensional EEG matrix was recovered.');
end

% Orient as samples x channels.
[a,b]=size(X);
if a<=128 && b>max(a,1000)
    X=X';
elseif b>128 && a<=128
    X=X';
elseif b<=128 && a>b
    % already samples x channels
elseif a<=128 && b>a
    X=X';
end

if size(X,2)<16
    error('Recovered matrix has only %d candidate channels.',size(X,2));
end

% Retain the first 64 EEG channels; a possible 65th trigger channel is not
% included in spectral analysis.
if size(X,2)>maxChannels
    X=X(:,1:maxChannels);
end

if isempty(labels) || numel(labels)<size(X,2)
    labels=default64Labels(size(X,2));
else
    labels=cellstr(string(labels(1:size(X,2))));
end

X=double(X);
end

function [X,labels,fs] = readEDFEEG(rawPath,fsDefault)
if exist('edfread','file')~=2
    error('edfread is unavailable in this MATLAB installation.');
end

info=[];
try; info=edfinfo(rawPath); catch; end
TT=edfread(rawPath);
X=tableLikeToMatrix(TT);
labels=TT.Properties.VariableNames;
fs=fsDefault;

if ~isempty(info)
    try; labels=cellstr(string(info.SignalLabels)); catch; end
    try
        dur=seconds(info.DataRecordDuration);
        fs0=double(info.NumSamples(1))/dur;
        if isfinite(fs0)&&fs0>0; fs=fs0; end
    catch
    end
end
end

function [X,labels,fs] = readMATEEG(rawPath,fsDefault)
X=[];
labels={};
fs=fsDefault;

try
    info=whos('-file',rawPath);
catch ME
    error('Cannot inspect MAT file: %s',ME.message);
end

% Recover scalar sampling-rate metadata when available.
rateNames=["fs","srate","samplingrate","samplerate","frequency"];
for i=1:numel(info)
    nm=lower(string(info(i).name));
    if any(nm==rateNames) && prod(info(i).size)==1 && ...
            any(strcmpi(info(i).class,{'double','single','int32','uint32'}))
        try
            S=load(rawPath,info(i).name);
            v=double(S.(info(i).name));
            if isfinite(v)&&v>0; fs=v; end
        catch
        end
    end
end

% Rank candidate variables without loading the full workspace.
scores=-Inf(numel(info),1);
for i=1:numel(info)
    sz=double(info(i).size);
    % Some unusual MAT variables can return empty or scalar size metadata.
    % Convert every case to a safe two-element size vector.
    if isempty(sz)
        sz=[0 0];
    elseif isscalar(sz)
        sz=[sz 1];
    else
        sz=sz(1:2);
    end
    a=sz(1); b=sz(2);
    small=min(a,b); large=max(a,b);
    nm=lower(string(info(i).name));
    cls=lower(string(info(i).class));

    if any(cls==["double","single","int16","int32","uint16", ...
            "uint32","logical"])
        if small>=16 && small<=128 && large>=1000
            scores(i)=100+log10(max(large,1))*5;
            if any(small==[64 65 66]); scores(i)=scores(i)+35; end
            if contains(nm,["eeg","data","signal","filtered"])
                scores(i)=scores(i)+20;
            end
        end
    elseif any(cls==["table","timetable"])
        if b>=16 && b<=128 && a>=1000
            scores(i)=90+log10(max(a,1))*5;
            if contains(nm,["eeg","data","signal"])
                scores(i)=scores(i)+20;
            end
        end
    elseif cls=="struct"
        if contains(nm,["eeg","data","signal","dataset"])
            scores(i)=50;
        end
    end
end

[sortedScores,ord]=sort(scores,'descend');
for k=1:numel(ord)
    if ~isfinite(sortedScores(k)); break; end
    nm=info(ord(k)).name;

    try
        S=load(rawPath,nm);
        value=S.(nm);
        [X0,labels0,fs0]=extractEEGValue(value,fs);

        if isUsableEEGMatrix(X0)
            X=X0;
            labels=labels0;
            if isfinite(fs0)&&fs0>0; fs=fs0; end
            break;
        end
    catch
    end
end

% Fallback: load likely named variables individually.
if isempty(X)
    fallbackNames={'EEG','eeg','data','Data','signal','signals','X','x'};
    available={info.name};
    for i=1:numel(fallbackNames)
        hit=find(strcmpi(available,fallbackNames{i}),1);
        if isempty(hit); continue; end
        try
            S=load(rawPath,available{hit});
            [X0,labels0,fs0]=extractEEGValue(S.(available{hit}),fs);
            if isUsableEEGMatrix(X0)
                X=X0; labels=labels0; fs=fs0;
                break;
            end
        catch
        end
    end
end

if isempty(X)
    error(['No EEG-like matrix was found in MAT file: %s. ' ...
        'Expected a matrix with approximately 64 channels and at least ' ...
        '1000 samples.'],rawPath);
end

% Recover channel labels from separate metadata variables if needed.
if isempty(labels)
    labelAliases=["chanlabels","channellabels","labels","channelnames"];
    for i=1:numel(info)
        nm=lower(regexprep(string(info(i).name),'[^a-z0-9]',''));
        if any(nm==labelAliases)
            try
                S=load(rawPath,info(i).name);
                labels=cellstr(string(S.(info(i).name)));
                break;
            catch
            end
        end
    end
end
end

function [X,labels,fs] = extractEEGValue(value,fsDefault)
X=[];
labels={};
fs=fsDefault;

if isnumeric(value) || islogical(value)
    if ismatrix(value)
        X=double(value);
    end
    return;
end

if istable(value) || istimetable(value)
    X=tableLikeToMatrix(value);
    try; labels=value.Properties.VariableNames; catch; end
    return;
end

if isstruct(value)
    % Sampling rate.
    rateFields={'srate','fs','samplingRate','SamplingRate','sampleRate'};
    for i=1:numel(rateFields)
        if isfield(value,rateFields{i})
            v=value.(rateFields{i});
            if isnumeric(v)&&isscalar(v)&&isfinite(v)&&v>0
                fs=double(v);
                break;
            end
        end
    end

    % Channel labels.
    if isfield(value,'chanlocs')
        try; labels={value.chanlocs.labels}; catch; end
    elseif isfield(value,'labels')
        try; labels=cellstr(string(value.labels)); catch; end
    elseif isfield(value,'chanLabels')
        try; labels=cellstr(string(value.chanLabels)); catch; end
    end

    dataFields={'data','Data','EEG','eeg','X','x','signal','signals'};
    for i=1:numel(dataFields)
        if isfield(value,dataFields{i})
            [X0,L0,fs0]=extractEEGValue(value.(dataFields{i}),fs);
            if isUsableEEGMatrix(X0)
                X=X0;
                if isempty(labels); labels=L0; end
                if isfinite(fs0)&&fs0>0; fs=fs0; end
                return;
            end
        end
    end
end
end

function tf = isUsableEEGMatrix(X)
tf=false;
if isempty(X)||~isnumeric(X)||~ismatrix(X);return;end
[a,b]=size(X);
small=min(a,b); large=max(a,b);
tf=small>=16 && small<=128 && large>=1000;
end

function X = tableLikeToMatrix(TT)
vars=TT.Properties.VariableNames;
cols=cell(0,1);

for i=1:numel(vars)
    x=TT.(vars{i});
    try
        if iscell(x)
            try
                x=vertcat(x{:});
            catch
                z=cellfun(@(v) v(:),x,'UniformOutput',false);
                x=vertcat(z{:});
            end
        elseif istable(x)||istimetable(x)
            x=table2array(x);
        end

        if isnumeric(x)||islogical(x)
            cols{end+1,1}=double(x(:)); %#ok<AGROW>
        end
    catch
    end
end

if isempty(cols)
    X=[];
    return;
end

L=min(cellfun(@numel,cols));
X=nan(L,numel(cols));
for i=1:numel(cols)
    X(:,i)=cols{i}(1:L);
end
end

