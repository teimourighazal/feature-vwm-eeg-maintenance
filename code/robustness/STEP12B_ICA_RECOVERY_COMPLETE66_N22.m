function r = estimateICARank(X,fs)
% Numerical rank from a subsampled covariance matrix. Average referencing
% normally limits the rank to <= Nchannels-1.
stride=max(1,round(fs/125));
Y=X(1:stride:end,:);
Y=Y-mean(Y,1,'omitnan');
C=(Y'*Y)/max(1,size(Y,1));
ev=sort(real(eig((C+C')/2)),'descend');
if isempty(ev) || max(ev)<=0
    r=0;
    return;
end
r=sum(ev>max(ev)*1e-7);
r=min(r,size(X,2)-1);
r=max(r,1);
end

function token = safePathToken(rawPath)
s=char(rawPath);
[~,base,ext]=fileparts(s);
base=regexprep([base ext],'[^A-Za-z0-9]','_');
% Deterministic lightweight path checksum to avoid collisions between runs
% with identical basenames in different subject folders.
u=double(uint8(s));
checksum=mod(sum(u.*(1:numel(u))),2^31-1);
token=sprintf('%s_%010d',base,round(checksum));
end

