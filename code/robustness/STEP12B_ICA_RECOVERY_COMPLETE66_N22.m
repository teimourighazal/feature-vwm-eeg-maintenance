function [Tomni,Tpair] = conditionStats(T,minN)
metrics=unique(T.EEGMetric,'stable');
phases=["stimulus","maintenance","retrieval"];
bands=unique(T.Band,'stable');
features=unique(T.FeatureName,'stable');
conds=["color","orientation","conjunction"];
pairs={1,2,"color_vs_orientation"; ...
       1,3,"color_vs_conjunction"; ...
       2,3,"orientation_vs_conjunction"};

orows=cell(0,14);
prows=cell(0,14);

for im=1:numel(metrics)
for ip=1:numel(phases)
for ib=1:numel(bands)
for jf=1:numel(features)
    S=T(T.EEGMetric==metrics(im) & T.PhaseLabel==phases(ip) & ...
        T.Band==bands(ib) & T.FeatureName==features(jf),:);

    [X,subj]=wideConditions(S);
    ok=all(isfinite(X),2);
    X=X(ok,:); subj=subj(ok);
    n=size(X,1);
    if n<minN; continue; end

    [pF,chi2,W]=friedmanStats(X);
    med=median(X,1,'omitnan');
    [~,mx]=max(med);

    orows(end+1,:)={string(S.AnalysisLevel(1)),metrics(im), ...
        phases(ip),bands(ib),features(jf),n,med(1),med(2),med(3), ...
        conds(mx),pF,chi2,W,strjoin(subj,'|')}; %#ok<AGROW>

    for k=1:3
        ia=pairs{k,1}; ibb=pairs{k,2};
        d=X(:,ia)-X(:,ibb);
        try; p=signrank(X(:,ia),X(:,ibb)); catch; p=NaN; end
        prows(end+1,:)={string(S.AnalysisLevel(1)),metrics(im), ...
            phases(ip),bands(ib),features(jf),string(pairs{k,3}),n, ...
            median(X(:,ia),'omitnan'),median(X(:,ibb),'omitnan'), ...
            median(d,'omitnan'),p,mean(d>0,'omitnan'), ...
            mean(d<0,'omitnan'),strjoin(subj,'|')}; %#ok<AGROW>
    end
end
end
end
end

if isempty(orows)
    Tomni=table();
else
    Tomni=cell2table(orows,'VariableNames', ...
        {'AnalysisLevel','EEGMetric','PhaseLabel','Band','FeatureName', ...
         'NSubjects','Median_color','Median_orientation', ...
         'Median_conjunction','MaxCondition','p_Friedman','ChiSquare', ...
         'KendallW','SubjectsUsed'});
    Tomni=standardizeOutputTable(Tomni);
