    comp={2,1,"maintenance_vs_stimulus"; ...
          2,3,"maintenance_vs_retrieval"};
    for k=1:2
        d=X(:,comp{k,1})-X(:,comp{k,2});
        try
            p=signrank(X(:,comp{k,1}),X(:,comp{k,2}), ...
                'tail','right');
