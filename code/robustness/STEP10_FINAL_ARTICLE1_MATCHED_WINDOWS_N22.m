function col = findColumn(T,aliases)
col='';
vars=T.Properties.VariableNames;
clean=lower(regexprep(vars,'[^A-Za-z0-9]',''));
for i=1:numel(aliases)
    key=lower(regexprep(aliases{i},'[^A-Za-z0-9]',''));
    hit=find(strcmp(clean,key),1);
    if ~isempty(hit);col=vars{hit};return;end
end
for i=1:numel(aliases)
    key=lower(regexprep(aliases{i},'[^A-Za-z0-9]',''));
    hit=find(contains(clean,key),1);
    if ~isempty(hit);col=vars{hit};return;end
end
end

function s = normalizeSubject(x)
raw=lower(strtrim(string(x)));s=strings(numel(raw),1);
for i=1:numel(raw)
    tok=regexp(raw(i),'s[_\-\s]*0*([0-9]{1,3})','tokens','once');
    if isempty(tok);tok=regexp(raw(i),'subject[_\-\s]*0*([0-9]{1,3})','tokens','once');end
    if isempty(tok);tok=regexp(raw(i),'^0*([0-9]{1,3})$','tokens','once');end
    if ~isempty(tok);s(i)="s"+string(str2double(tok{1}));else;s(i)=raw(i);end
end
end

function r = normalizeRun(x)
raw=lower(strtrim(string(x)));r=strings(numel(raw),1);
for i=1:numel(raw)
    tok=regexp(raw(i),'run[_\-\s]*0*([0-9]{1,2})','tokens','once');
    if isempty(tok);tok=regexp(raw(i),'^0*([0-9]{1,2})$','tokens','once');end
    if ~isempty(tok);r(i)="run"+string(str2double(tok{1}));else;r(i)=raw(i);end
end
end

function t = normalizeTrial(x)
raw=strtrim(string(x));t=strings(numel(raw),1);
for i=1:numel(raw)
    v=str2double(raw(i));
    if isfinite(v);t(i)=string(round(v));else;t(i)=raw(i);end
end
end

function c = normalizeCondition(x)
s=lower(strtrim(string(x)));c=strings(numel(s),1);
for i=1:numel(s)
    if any(s(i)==["1","color","color_only","color-only","coloronly","c"])
        c(i)="color";
    elseif any(s(i)==["2","orientation","ori","orientation_only", ...
            "orientation-only","orientationonly","o"])
        c(i)="orientation";
    elseif any(s(i)==["3","conjunction","conj","binding"])
        c(i)="conjunction";
    else
        c(i)=s(i);
    end
end
end

function p = normalizePhase(x)
s=lower(strtrim(string(x)));p=strings(numel(s),1);
for i=1:numel(s)
    if contains(s(i),'stim');p(i)="stimulus";
    elseif contains(s(i),'maint')||contains(s(i),'delay')
        p(i)="maintenance";
    elseif contains(s(i),'retr')||contains(s(i),'probe')|| ...
            contains(s(i),'test')
        p(i)="retrieval";
    else;p(i)=s(i);
    end
end
end

