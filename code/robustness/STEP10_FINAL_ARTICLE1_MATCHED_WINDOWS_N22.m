function D = manuscriptDecisionFinal(counts,comp,erp)
nComp=0;nERP=0;
if ~isempty(comp);nComp=sum(comp.StrongSupport,'omitnan');end
if ~isempty(erp);nERP=sum(erp.StrongSupport,'omitnan');end

maintMost=false;
if ~isempty(counts)
    votes=false(0,1);
    levels=unique(counts.AnalysisLevel,'stable');
    metrics=unique(counts.EEGMetric,'stable');
    for i=1:numel(levels)
        for j=1:numel(metrics)
            S=counts(counts.AnalysisLevel==levels(i)& ...
                counts.EEGMetric==metrics(j),:);
            ns=phaseCountValue(S,"stimulus");
            nm=phaseCountValue(S,"maintenance");
            nr=phaseCountValue(S,"retrieval");
            if all(isfinite([ns nm nr]))
                votes(end+1,1)=nm>ns&&nm>nr; %#ok<AGROW>
            end
        end
    end
    if ~isempty(votes);maintMost=mean(votes)>=.5;end
end

if nComp>=1 && nERP>=1
    decision="strongest_supported";
    wording="were strongest during maintenance";
    rationale="Equal-0.6-s direct phase sensitivity showed corrected maintenance dominance in at least one focused spectral index and at least one ERP feature.";
elseif maintMost
    decision="predominantly_observed";
    wording="were predominantly observed during maintenance";
    rationale="Equal-0.6-s corrected condition effects were concentrated during maintenance, but direct strong support was not established in both focused spectral and ERP families.";
else
    decision="phase_specific_only";
    wording="showed phase-specific differences";
    rationale="The equal-0.6-s sensitivity and direct phase analyses did not support a general maintenance-dominance claim.";
end

D=table(decision,wording,rationale,nComp,nERP,maintMost, ...
    'VariableNames',{'Decision','RecommendedWording','Rationale', ...
    'NStrongFocusedIndices','NStrongERPFeatures', ...
    'MaintenanceHasMostSignificantEffects'});
end

