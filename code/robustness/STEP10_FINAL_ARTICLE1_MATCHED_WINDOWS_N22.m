    w=ones(n,1);
else
    w=0.54-0.46*cos(2*pi*(0:n-1)'/(n-1));
end
end

function [bp,rp] = bandPowerOriginalStyle(seg,fs,bands)
% Matches the FFT logic used by build_phase_features/bandpower_fft:
% mean removal, nfft=nextpow2(n), one-sided spectrum, trapz integration.
seg=double(seg);
n=size(seg,1);
nCh=size(seg,2);
nB=size(bands,1);

bp=nan(nCh,nB);
for ch=1:nCh
    x=seg(:,ch);
    x=x-mean(x,'omitnan');
    x(~isfinite(x))=0;

    nfft=2^nextpow2(n);
    F=fft(x,nfft);
    P2=abs(F/nfft).^2;
    P1=P2(1:floor(nfft/2)+1);
    freq=fs*(0:floor(nfft/2))/nfft;

    for ib=1:nB
        idx=freq>=bands(ib,1) & freq<=bands(ib,2);
        if any(idx)
            bp(ch,ib)=trapz(freq(idx),P1(idx));
        end
    end
end

den=sum(bp,2,'omitnan');
rp=bp./den;
rp(~isfinite(rp))=NaN;
end

