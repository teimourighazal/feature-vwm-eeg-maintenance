end

function p = firstExistingFile(candidates)
p='';
for i=1:numel(candidates)
    if exist(candidates{i},'file')==2
        p=candidates{i};
        return;
    end
end
end

function M = standardizeMergedTable(T)
M=table();

sc=findColumn(T,{'Subject','SubjectID','Subj','Participant'});
rc=findColumn(T,{'Run','RunID','RunLabel'});
tc=findColumn(T,{'Trial','TrialNum','TrialNumber','TrialID','TrialIndex'});
cc=findColumn(T,{'ConditionLabel','Condition','TaskCondition','Cond'});
pc=findColumn(T,{'PhaseLabel','Phase','MemoryPhase'});
oc=findColumn(T,{'PhaseStartSample','StartSample','SampleOnset', ...
    'EventSample','OnsetSample','Start'});
ec=findColumn(T,{'RawEEGPath','EDFPath','EDFFile','RawPath', ...
    'RawFile','EEGFile','FilePath','SourceFile'});

required={sc,cc,pc,oc};
if any(cellfun(@isempty,required))
    error(['Merged trial-phase table lacks required subject, condition, ' ...
        'phase, or phase-start columns.']);
end

M.Subject=normalizeSubject(T.(sc));
if isempty(rc)
    M.Run=repmat("",height(T),1);
else
    M.Run=normalizeRun(T.(rc));
end
