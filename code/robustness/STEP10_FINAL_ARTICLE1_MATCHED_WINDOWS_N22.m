function [rho,p,n] = spearmanSafe(x,y)
x=double(x(:)); y=double(y(:));
ok=isfinite(x)&isfinite(y);
x=x(ok); y=y(ok); n=numel(x);
rho=NaN; p=NaN;
if n<5; return; end
try
    [rho,p]=corr(x,y,'Type','Spearman','Rows','complete');
catch
    rx=tiedrank(x); ry=tiedrank(y);
    C=corrcoef(rx,ry);
    rho=C(1,2);
    if n>2 && abs(rho)<1
        t=rho*sqrt((n-2)/(1-rho^2));
        p=2*(1-tcdf(abs(t),n-2));
    end
end
end

