    'FileName','BaseName','Extension','ParentFolder','BestVariable', ...
    'Inspection','OriginalRawEEGPath','RawPathMatchMode'};

for i=1:numel(stringVars)
    v=stringVars{i};
    if ismember(v,T.Properties.VariableNames)
        T.(v)=string(T.(v));
    end
end

logicalVars={'IsRestingLike','IsWorkspace','IsDerivedLike', ...
    'EEGLike','FileExists','ReadOK','MaintenanceDominant', ...
    'StrongSupport'};
for i=1:numel(logicalVars)
