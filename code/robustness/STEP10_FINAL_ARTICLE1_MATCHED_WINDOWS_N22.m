    'Median_A','Median_B','MedianDiff_AminusB','p_Signrank', ...
    'Proportion_AgtB','Proportion_AltB','NTests','NSignificantFDR', ...
    'MedianKendallW','MaximumKendallW','MedianP', ...
    'ProportionSignificant','ColorValue','OrientationValue', ...
    'ConjunctionValue','EffectMagnitude','MaximumConditionValue', ...
    'MinimumConditionValue','MedianEffect_Stimulus', ...
    'MedianEffect_Maintenance','MedianEffect_Retrieval', ...
    'p_PhaseFriedman','Median_Maintenance','Median_Comparator', ...
    'MedianDifference','p_OneSidedSignrank', ...
    'Proportion_MaintenanceGreater','FeatureValue', ...
