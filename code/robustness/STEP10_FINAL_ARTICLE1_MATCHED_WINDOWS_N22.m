    x=R(base&R.Band=="alpha"& ...
        ismember(R.ROI,["parietal","parieto_occipital","occipital"]),:);
    v1=median(x.LogAbsPower,'omitnan');

    x=R(base&R.Band=="gamma"& ...
        ismember(R.ROI,["parietal","parieto_occipital"]),:);
    v2=median(x.RelPower,'omitnan');

    post=R(base&R.Band=="alpha"& ...
        ismember(R.ROI,["centroparietal","parietal", ...
        "parieto_occipital","occipital"]),:);
    ant=R(base&R.Band=="alpha"& ...
        ismember(R.ROI,["frontal","frontocentral"]),:);
    v3=median(post.RelPower,'omitnan')-median(ant.RelPower,'omitnan');

    rows(end+1,:)={keys.Subject(i),keys.ConditionLabel(i), ...
        keys.PhaseLabel(i),"alpha","posterior_alpha_log_power", ...
        "log_absolute_power",v1,"focused_index"}; %#ok<AGROW>
    rows(end+1,:)={keys.Subject(i),keys.ConditionLabel(i), ...
        keys.PhaseLabel(i),"gamma","posterior_gamma_relative_power", ...
        "relative_power",v2,"focused_index"}; %#ok<AGROW>
    rows(end+1,:)={keys.Subject(i),keys.ConditionLabel(i), ...
        keys.PhaseLabel(i),"alpha", ...
        "posterior_minus_anterior_alpha_relative_power", ...
        "relative_power",v3,"focused_index"}; %#ok<AGROW>
end

C=cell2table(rows,'VariableNames', ...
    {'Subject','ConditionLabel','PhaseLabel','Band','FeatureName', ...
     'EEGMetric','FeatureValue','AnalysisLevel'});
C=standardizeOutputTable(C);
C.NTrials=nan(height(C),1);
end

function D = buildDirectionalContrasts(C)
keys=unique(C(:,{'Subject','EEGMetric','Band','FeatureName', ...
    'PhaseLabel','AnalysisLevel'}),'rows','stable');
rows=cell(0,9);

for i=1:height(keys)
    S=C(C.Subject==keys.Subject(i)&C.EEGMetric==keys.EEGMetric(i)& ...
        C.Band==keys.Band(i)&C.FeatureName==keys.FeatureName(i)& ...
        C.PhaseLabel==keys.PhaseLabel(i),:);

    c=conditionValue(S,"color");
    o=conditionValue(S,"orientation");
    j=conditionValue(S,"conjunction");
    if ~all(isfinite([c o j]));continue;end

    if keys.FeatureName(i)=="posterior_gamma_relative_power"
        v=mean([o j])-c;
        definition="mean_orientation_conjunction_minus_color";
    else
        v=c-mean([o j]);
        definition="color_minus_mean_orientation_conjunction";
    end

    rows(end+1,:)={keys.Subject(i),keys.EEGMetric(i), ...
        keys.Band(i),keys.FeatureName(i),keys.PhaseLabel(i), ...
        keys.AnalysisLevel(i),v,definition,v}; %#ok<AGROW>
end

D=cell2table(rows,'VariableNames', ...
    {'Subject','EEGMetric','Band','FeatureName','PhaseLabel', ...
     'AnalysisLevel','DirectionalContrast','IndexDefinition', ...
     'EffectMagnitude'});
D=standardizeOutputTable(D);
end

